# Crie uma classe "Calculadora".
# Ela deverá possuir o atributo "x", que representa o número atual armazenado na memória da calculadora. Inicialmente ele é zero.

# Faça os métodos:
# soma -> recebe como parâmetro um número y e adiciona-o ao atributo self.x
# sub -> recebe como parâmetro um número y e subtrai-o do atributo self.x
# mult -> recebe como parâmetro um número y e redefine o self.x como o produto do x pelo y
# div -> recebe como parâmetro um número y e redefine o self.x como o produto do x pelo y

# Faça então um programa que instancie uma calculadora e execute um loop indefinido (while true) em que o usuário insere uma operação e um número, e então efetuar a operação utilizando os métodos do objeto calculadora, e exibir o resultado na tela. 
# O programa se encerra quando o usuário digitar "sair".